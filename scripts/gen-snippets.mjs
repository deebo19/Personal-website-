// Copies the real QA framework files into the app at build time, so the
// "How I test" page always shows the code that actually runs in CI.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const files = [
  "qa/pages/base_page.py",
  "qa/pages/components/hero.py",
  "qa/tests/test_hero.py",
  "qa/pages/components/feedback_form.py",
  "qa/tests/test_feedback.py",
  "qa/tests/test_highlights.py",
  "qa/conftest.py",
  "qa/pytest.ini",
];

const snippets = Object.fromEntries(files.map((f) => [f, readFileSync(f, "utf8").trimEnd()]));
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/snippets.ts",
  "// Generated by scripts/gen-snippets.mjs. Do not edit.\n" +
    `export const SNIPPETS: Record<string, string> = ${JSON.stringify(snippets, null, 2)};\n`
);
console.log(`Wrote ${files.length} snippets to src/generated/snippets.ts`);
